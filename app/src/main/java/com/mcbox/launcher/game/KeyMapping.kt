    fun glfwKey(androidKeyCode: Int): Int = map[androidKeyCode] ?: 0

    fun hasMapping(androidKeyCode: Int): Boolean = (map[androidKeyCode] ?: 0) != 0

    fun sendKeyEvent(event: KeyEvent, charMods: Int = -1) {
        val glfwKey = glfwKey(event.keyCode)
        if (glfwKey == 0) return
        val mods = if (charMods >= 0) charMods else modsOf(event)
        CallbackBridge.setModifiers(glfwKey, event.action == KeyEvent.ACTION_DOWN)
        val isDown = event.action == KeyEvent.ACTION_DOWN
        val ch = event.unicodeChar.toChar()
        CallbackBridge.sendKeyPress(glfwKey, ch, event.scanCode, mods, isDown)
    }

    fun modsOf(event: KeyEvent): Int {
        var mods = 0
        if (event.isShiftPressed) mods = mods or 1
        if (event.isCtrlPressed) mods = mods or 2
        if (event.isAltPressed) mods = mods or 4
        if (event.isMetaPressed) mods = mods or 8
        return mods
    }

    fun sendMouseButton(glfwButton: Int, down: Boolean) {
        CallbackBridge.sendMouseButton(glfwButton, down)
    }

    fun sendMouseMove(x: Float, y: Float) {
        CallbackBridge.sendCursorPos(x, y)
    }

    fun sendScroll(dx: Double, dy: Double) {
        CallbackBridge.sendScroll(dx, dy)
    }
